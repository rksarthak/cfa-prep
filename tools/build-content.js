#!/usr/bin/env node
/*
 * Builds the paid-module files from content-paid/<subject>/*.js
 *   1. supabase/paid-content/<subject>-mNN.sql  (run each in Supabase SQL Editor to upload / update a module)
 *   2. public/js/content/paid-meta.js            (public outline only: titles and question counts, no lesson content)
 * Usage: node tools/build-content.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "content-paid");
const sqlDir = path.join(root, "supabase", "paid-content");
fs.mkdirSync(sqlDir, { recursive: true });

const meta = {};
let count = 0;
for (const subject of fs.readdirSync(srcDir).sort()) {
  const dir = path.join(srcDir, subject);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
    const mods = [];
    const tests = [];
    const sandbox = { CFA: { registerModule: (sid, mod) => mods.push([sid, mod]), registerTest: (sid, t) => tests.push([sid, t]) } };
    vm.runInNewContext(fs.readFileSync(path.join(dir, file), "utf8"), sandbox, { filename: file });
    // End-of-subject test: the first freeCount questions become a public file; the rest go to the database as module 99.
    for (const [sid, t] of tests) {
      const n = t.freeCount || 10;
      const free = { title: t.title, intro: t.intro, freeCount: n, free: t.questions.slice(0, n), paidCount: t.questions.length - n };
      fs.mkdirSync(path.join(root, "public", "js", "content", sid), { recursive: true });
      fs.writeFileSync(path.join(root, "public", "js", "content", sid, "test-free.js"),
        "/* Generated by tools/build-content.js: free part of the " + sid + " subject test (questions 1-" + n + "). */\n" +
        "CFA.registerTest(" + JSON.stringify(sid) + ", " + JSON.stringify(free, null, 1) + ");\n");
      const json = JSON.stringify({ num: 99, title: t.title, questions: t.questions.slice(n) });
      let tag = "cfa";
      while (json.includes("$" + tag + "$")) tag += "x";
      fs.writeFileSync(path.join(sqlDir, `${sid}-test.sql`),
        `-- ${sid} subject test, paid part (questions ${n + 1}-${t.questions.length}). Generated by tools/build-content.js. Run in Supabase SQL Editor.\n` +
        `insert into public.module_content (subject_id, num, title, content, updated_at)\nvalues ('${sid}', 99, $${tag}$${t.title}$${tag}$, $${tag}$${json}$${tag}$::jsonb, now())\n` +
        `on conflict (subject_id, num) do update set title = excluded.title, content = excluded.content, updated_at = now();\n`);
      count++;
    }
    for (const [sid, mod] of mods) {
      const json = JSON.stringify(mod);
      let tag = "cfa";
      while (json.includes("$" + tag + "$") || mod.title.includes("$" + tag + "$")) tag += "x";
      const nn = String(mod.num).padStart(2, "0");
      const sql =
        `-- ${sid} module ${mod.num}: ${mod.title}\n-- Generated by tools/build-content.js from content-paid/${subject}/${file}. Run in Supabase SQL Editor.\n` +
        `insert into public.module_content (subject_id, num, title, content, updated_at)\nvalues ('${sid}', ${mod.num}, $${tag}$${mod.title}$${tag}$, $${tag}$${json}$${tag}$::jsonb, now())\n` +
        `on conflict (subject_id, num) do update set title = excluded.title, content = excluded.content, updated_at = now();\n`;
      fs.writeFileSync(path.join(sqlDir, `${sid}-m${nn}.sql`), sql);
      meta[sid + "/" + mod.num] = {
        title: mod.title,
        lessons: mod.lessons.map((l) => ({ id: l.id, title: l.title, summary: l.summary, questions: l.quiz.length })),
        moduleQuiz: (mod.moduleQuiz || []).length
      };
      count++;
    }
  }
}
fs.writeFileSync(
  path.join(root, "public", "js", "content", "paid-meta.js"),
  "/* Generated by tools/build-content.js: public outline of paid modules (no lesson content). */\nCFA.paidMeta = " +
    JSON.stringify(meta, null, 1) + ";\n"
);
console.log(`Built ${count} paid module(s).`);
