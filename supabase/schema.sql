-- CFA Level I Prep: database setup.
-- Run once in Supabase: SQL Editor → New query → paste → Run.

-- One row per student per quiz (lesson quiz or module quiz).
create table if not exists public.progress (
  user_id     uuid        not null references auth.users (id) on delete cascade,
  item_key    text        not null,          -- e.g. "fsa/1/l3" or "fsa/1/module-quiz"
  best        integer     not null default 0,
  last_score  integer     not null default 0,
  total       integer     not null default 0,
  attempts    integer     not null default 0,
  updated_at  timestamptz not null default now(),
  primary key (user_id, item_key)
);

-- Row Level Security: a student can only see and change their own rows.
alter table public.progress enable row level security;

drop policy if exists "read own progress"   on public.progress;
drop policy if exists "insert own progress" on public.progress;
drop policy if exists "update own progress" on public.progress;
drop policy if exists "delete own progress" on public.progress;

create policy "read own progress"   on public.progress for select using (auth.uid() = user_id);
create policy "insert own progress" on public.progress for insert with check (auth.uid() = user_id);
create policy "update own progress" on public.progress for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "delete own progress" on public.progress for delete using (auth.uid() = user_id);

-- ============================================================
-- Subject purchases (UPI QR payments, approved by an admin)
-- Safe to run again: everything below uses "if not exists" / "drop … if exists".
-- ============================================================

-- Who may approve payments. Add yourself after signing up once on the site:
--   insert into public.admins (user_id) select id from auth.users where email = 'you@example.com';
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.admins enable row level security;
drop policy if exists "see own admin row" on public.admins;
create policy "see own admin row" on public.admins for select using (auth.uid() = user_id);

create or replace function public.is_admin() returns boolean
  language sql stable security definer set search_path = public
  as $$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

create table if not exists public.purchases (
  id          bigint generated always as identity primary key,
  user_id     uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  email       text,
  subject_id  text        not null,                 -- e.g. "fsa"
  amount_inr  integer     not null default 399,
  method      text        not null default 'upi_qr',
  reference   text,                                 -- UPI transaction ID (UTR) typed by the student
  status      text        not null default 'pending' check (status in ('pending', 'paid', 'rejected')),
  note        text,                                 -- admin note, e.g. reason for rejection
  created_at  timestamptz not null default now(),
  reviewed_at timestamptz
);

-- One open (pending or paid) purchase per student per subject, and a UTR can only be used once.
create unique index if not exists purchases_one_open_per_subject on public.purchases (user_id, subject_id) where status <> 'rejected';
create unique index if not exists purchases_reference_once on public.purchases (reference) where status <> 'rejected';

alter table public.purchases enable row level security;
drop policy if exists "student reads own purchases"  on public.purchases;
drop policy if exists "student creates pending"      on public.purchases;
drop policy if exists "admin reads all purchases"    on public.purchases;
drop policy if exists "admin updates purchases"      on public.purchases;

-- Students: see their own rows, and create a row only as 'pending' for themselves. They can never mark it paid.
create policy "student reads own purchases" on public.purchases for select using (auth.uid() = user_id);
create policy "student creates pending"     on public.purchases for insert with check (auth.uid() = user_id and status = 'pending');
-- Admins: see and update every row (approve / reject).
create policy "admin reads all purchases"   on public.purchases for select using (public.is_admin());
create policy "admin updates purchases"     on public.purchases for update using (public.is_admin()) with check (public.is_admin());

-- ============================================================
-- Paid module content (modules 3+). Only buyers of the subject (and admins) can read it.
-- Content is uploaded with the SQL files in supabase/paid-content/ (generated by tools/build-content.js).
-- ============================================================
create table if not exists public.module_content (
  subject_id  text        not null,
  num         integer     not null,
  title       text,
  content     jsonb       not null,
  updated_at  timestamptz not null default now(),
  primary key (subject_id, num)
);
alter table public.module_content enable row level security;
drop policy if exists "buyers read paid content" on public.module_content;
create policy "buyers read paid content" on public.module_content for select using (
  public.is_admin()
  or exists (
    select 1 from public.purchases p
    where p.user_id = auth.uid() and p.subject_id = module_content.subject_id and p.status = 'paid'
  )
);
-- No insert/update policies: content is only changed from the SQL Editor (which bypasses these rules).
